@main.route("/templates/<template_id>")
@login_required
def template_detail(template_id):
    template = TEMPLATES.get(template_id)

    if template is None:
        flash("Шаблон не найден.", "error")
        return redirect(url_for("main.templates_page"))

    # Создаём копию шаблона, чтобы не менять исходные данные.
    template = dict(template)

    # Добавляем информацию об оригинальном файле и источнике.
    metadata = TEMPLATE_METADATA.get(template_id, {})
    template.update(metadata)

    return render_template(
        "template_detail.html",
        user=current_user,
        template=template
    )

@main.route("/templates/<template_id>/download")
@login_required
def download_template_file(template_id):
    template = TEMPLATES.get(template_id)

    if template is None:
        abort(404)

    metadata = TEMPLATE_METADATA.get(template_id, {})
    filename = metadata.get("original_file")

    if not filename:
        flash(
            "Оригинальный файл для этого шаблона пока не добавлен.",
            "info"
        )
        return redirect(
            url_for("main.template_detail", template_id=template_id)
        )

    # Разрешаем скачивание только PDF и DOCX.
    if (
        not isinstance(filename, str)
        or os.path.basename(filename) != filename
        or os.path.splitext(filename)[1].lower() not in {".pdf", ".docx"}
    ):
        abort(404)

    documents_dir = os.path.join(
        current_app.root_path,
        "legal_documents"
    )

    if not os.path.isfile(os.path.join(documents_dir, filename)):
        flash("Оригинальный файл пока не найден.", "info")
        return redirect(
            url_for("main.template_detail", template_id=template_id)
        )

    return send_from_directory(
        documents_dir,
        filename,
        as_attachment=True
    )




