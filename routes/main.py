@main.route("/ai-assistant", methods=["GET", "POST"])
@login_required
def ai_assistant():
    result = None
    filename = None

    if request.method == "POST":
        query = request.form.get("query", "").strip()
        uploaded_file = request.files.get("file")
        file_path = None

        if uploaded_file and uploaded_file.filename:
            original_filename = uploaded_file.filename.strip()
            extension = original_filename.rsplit(".", 1)[-1].lower() if "." in original_filename else ""

            if extension not in {"pdf", "docx", "txt"}:
                flash("Можно загружать только PDF, DOCX или TXT.", "error")
                return redirect(url_for("main.ai_assistant"))

            safe_filename = secure_filename(original_filename)
            unique_filename = f"{uuid.uuid4().hex}_{safe_filename}"

            upload_dir = os.path.join(
                current_app.root_path,
                "uploads",
                str(current_user.id),
                "assistant"
            )
            os.makedirs(upload_dir, exist_ok=True)

            file_path = os.path.join(upload_dir, unique_filename)
            uploaded_file.save(file_path)
            filename = original_filename

        if not query and not file_path:
            flash("Введите вопрос или загрузите документ.", "error")
            return redirect(url_for("main.ai_assistant"))

        try:
            result = analyze_document(text=query, file_path=file_path)
        except Exception:
            current_app.logger.exception("Ошибка AI-анализа")
            flash(
                "Не удалось выполнить AI-анализ. Проверьте подключение Dify.",
                "error"
            )

    return render_template(
        "ai_assistant.html",
        user=current_user,
        result=result,
        filename=filename
    )


